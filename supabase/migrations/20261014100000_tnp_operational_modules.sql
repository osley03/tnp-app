CREATE OR REPLACE FUNCTION public.tnp_prepare_dispute() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE l public.leases;
BEGIN
 IF TG_OP='INSERT' THEN
  SELECT * INTO l FROM public.leases WHERE id=NEW.lease_id;
  IF l.id IS NULL OR (auth.uid() IS NOT NULL AND NOT public.has_role(auth.uid(),'admin') AND auth.uid() NOT IN(l.tenant_id,l.landlord_id)) THEN RAISE EXCEPTION 'A dispute must belong to your lease'; END IF;
  NEW.property_id:=l.property_id; NEW.tenant_id:=l.tenant_id; NEW.landlord_id:=l.landlord_id;
  NEW.against_user:=CASE WHEN NEW.opened_by=l.tenant_id THEN l.landlord_id ELSE l.tenant_id END;
  NEW.status:='open'; NEW.reference:=coalesce(NEW.reference,'TNP-DSP-'||NEW.id::text);
 ELSIF auth.uid() IS NOT NULL AND NOT public.has_role(auth.uid(),'admin') THEN
  IF (to_jsonb(NEW)-ARRAY['landlord_response','status','updated_at']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['landlord_response','status','updated_at']) OR NEW.status NOT IN('open','under_review','awaiting_response','escalated') THEN RAISE EXCEPTION 'Only a response or escalation can be submitted'; END IF;
 END IF;
 NEW.updated_at:=now(); RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tnp_prepare_dispute ON public.disputes;
CREATE TRIGGER tnp_prepare_dispute BEFORE INSERT OR UPDATE ON public.disputes FOR EACH ROW EXECUTE FUNCTION public.tnp_prepare_dispute();
